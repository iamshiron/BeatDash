namespace Shiron.BeatDash.API.Configuration;

/// <summary>
/// Single-user desktop mode. There are no accounts to register or log into: one local user owns all
/// data, and the embedding desktop shell signs its web view in with a per-launch session token.
/// </summary>
public sealed class DesktopOptions {
    /// <summary>The shortest accepted <see cref="SessionToken"/>.</summary>
    public const int MinimumSessionTokenLength = 32;

    /// <summary>Runs the server in single-user desktop mode.</summary>
    public bool Enabled { get; set; }

    /// <summary>Secret that signs a web view in as the local user; generated by the desktop shell on every launch.</summary>
    public string SessionToken { get; set; } = "";
}
